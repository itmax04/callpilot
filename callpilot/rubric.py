from dataclasses import dataclass

@dataclass(frozen=True)
class Criterion:
    id: int; name: str; rule: str; boundary: str
CRITERIA = [
 Criterion(1,"Представление и цель","Продавец представился и обозначил цель/повестку.","Короткое приветствие без цели = insufficient_data, если дальше цель не ясна."),
 Criterion(2,"Выявление потребности","Есть вопрос или отражение конкретной потребности клиента.","Общие слова без потребности = not_met; если запись обрывается до этой части = insufficient_data."),
 Criterion(3,"Уточняющие вопросы","Есть минимум один вопрос, уточняющий контекст, ограничения или критерии.","Вопрос о времени/бюджете считается только если уточняет задачу; отсутствие нужной части = insufficient_data."),
 Criterion(4,"Связь предложения с потребностью","Предложение связано с ранее названной потребностью.","Презентация без связи = not_met; без выявленной потребности = insufficient_data."),
 Criterion(5,"Работа с возражениями","Возражение распознано и на него дан содержательный ответ.","Если возражений нет, status=not_applicable, это не штраф."),
 Criterion(6,"Конкретный следующий шаг","Согласованы действие и срок/ответственный либо конкретная встреча.","Расплывчатое 'будем на связи' = not_met; оборванный конец = insufficient_data."),
 Criterion(7,"Итоги и понимание","Продавец резюмирует договорённости и проверяет понимание.","Краткое 'спасибо' не итог; отсутствующий финал = insufficient_data."),
]
RUBRIC_VERSION="1.0-educational"

def rubric_text(version: str) -> str:
    extra = " Требуй минимум один точный quote и utterance_id для met/not_met, не выдумывай цитаты." if version == "v2" else ""
    return "\n".join(f"{c.id}. {c.name}: {c.rule} Граница: {c.boundary}" for c in CRITERIA)+extra
